// CSV export utilities

import { fmtRange } from './dates'

const BOM = '\uFEFF' // makes Excel read UTF-8 (₱, ñ) correctly

/** Quote a cell; neutralise formula-injection on strings. */
export function cell(value, delimiter) {
  if (value === null || value === undefined) return ''
  let s = String(value)
  if (typeof value === 'string' && /^[=+\-@\t\r]/.test(s)) s = `'${s}`
  const mustQuote = s.includes('"') || s.includes('\n') || s.includes('\r') || s.includes(delimiter)
  return mustQuote ? `"${s.replace(/"/g, '""')}"` : s
}

export const line = (cells, delimiter) => cells.map((c) => cell(c, delimiter)).join(delimiter)

/**
 * Build one text file. Multiple datasets are written as titled sections
 * separated by a blank line.
 */
export function buildExport({ datasets, data, delimiter, includeHeader, includeTotals, range, org, user, now = new Date() }) {
  const out = []

  if (includeHeader) {
    out.push(
      line(['BizzyQCU Seller Portal: Export Report'], delimiter),
      line(['Organization', org], delimiter),
      line(['Date Range', fmtRange(range.start, range.end)], delimiter),
      line(['Generated At', now.toLocaleString('en-PH')], delimiter),
      line(['Generated By', user], delimiter),
      line(['Officer Signature', '______________________'], delimiter),
      '',
    )
  }

  datasets.forEach((ds, i) => {
    const rows = ds.toRows(data)
    out.push(line([`# ${ds.title}`], delimiter), line(ds.columns, delimiter))
    rows.forEach((r) => out.push(line(r, delimiter)))

    if (includeTotals && ds.sumColumns?.length) {
      const totals = ds.columns.map((col, idx) =>
        idx === 0 ? 'TOTAL' : ds.sumColumns.includes(col)
          ? rows.reduce((sum, r) => sum + (Number(r[idx]) || 0), 0)
          : ''
      )
      out.push(line(totals, delimiter))
    }
    if (i < datasets.length - 1) out.push('')
  })

  return BOM + out.join('\r\n')
}

export function downloadText(text, filename, mime) {
  const url = URL.createObjectURL(new Blob([text], { type: `${mime};charset=utf-8` }))
  const a = Object.assign(document.createElement('a'), { href: url, download: filename })
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
}

export const formatBytes = (n) => (n < 1024 ? `${n} B` : `~${Math.max(1, Math.round(n / 1024))} KB`)
